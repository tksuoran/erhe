from erhe_codegen import *

# Generation defaults of the editor's LOD window (doc/editor/lod.md,
# doc/plans/lod.md section 2.5). The fields mirror
# erhe::primitive::Lod_settings; the window starts from these values.
struct("Lod_config",
    version=1,
    short_desc="Level of Detail",
    long_desc="Default LOD generation settings of the LOD window (erhe::primitive::Lod_settings).",
    developer=False,
    fields=[
        field("level_count", Int, added_in=1, default="6",
            short_desc="Levels",
            long_desc="Total number of levels, level 0 included.",
            ui_min="1", ui_max="8", hard_min="1", hard_max="8"),
        field("ratio", Float, added_in=1, default="0.5f",
            short_desc="Ratio",
            long_desc="Target index count of each level relative to the previous level.",
            ui_min="0.05f", ui_max="0.95f", hard_min="0.01f", hard_max="0.99f"),
        field("attributes", EnumRef("Lod_attribute_set"), added_in=1, default="Lod_attribute_set::normals_and_colors",
            short_desc="Attributes",
            long_desc="Vertex attributes the simplifier's error metric weighs besides the positions."),
        field("normal_weight", Float, added_in=1, default="1.0f",
            short_desc="Normal Weight",
            long_desc="Weight of the normals in the error metric.",
            ui_min="0.0f", ui_max="4.0f", hard_min="0.0f"),
        field("color_weight", Float, added_in=1, default="1.0f",
            short_desc="Color Weight",
            long_desc="Weight of the vertex colors in the error metric.",
            ui_min="0.0f", ui_max="4.0f", hard_min="0.0f"),
        field("border", EnumRef("Lod_border_mode"), added_in=1, default="Lod_border_mode::locked",
            short_desc="Border",
            long_desc="Locked keeps border vertices in place, so meshes split into several primitives do not crack apart."),
        field("seams", EnumRef("Lod_seam_mode"), added_in=1, default="Lod_seam_mode::keep",
            short_desc="Seams",
            long_desc="Keep: collapses never cross texture seams. Permissive: they may."),
        field("fallback", EnumRef("Lod_fallback_mode"), added_in=1, default="Lod_fallback_mode::none",
            short_desc="Fallback",
            long_desc="Sloppy: a level that misses its target takes a meshopt_simplifySloppy result when that is smaller."),
        field("normal_merge_angle", Float, added_in=1, default="20.0f",
            short_desc="Normal Merge Angle",
            long_desc="Degrees. Vertices at one position whose other attributes match are welded for simplification when their normals lie within this angle.",
            ui_min="0.0f", ui_max="180.0f", hard_min="0.0f", hard_max="180.0f"),
    ],
)
