[[nodiscard]] constexpr auto combine_property_row_scope(const uint64_t scope, const uint64_t value) -> uint64_t
{
    uint64_t x = scope ^ (value + 0x9e3779b97f4a7c15ull + (scope << 6) + (scope >> 2));
    x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9ull;
    x = (x ^ (x >> 27)) * 0x94d049bb133111ebull;
    return x ^ (x >> 31);
}

// What tells an entry apart from the other entries of its group. `instance`
// distinguishes repeats of one row: an index, an item id, an object address.
class Property_row_key
{
public:
    enum class Kind : uint32_t
    {
        row             = 0, // id: Property_row_id
        property        = 1, // id: Dependency_property::get_index()
        property_group  = 2, // id: Property_ui::group_id
        property_action = 3  // id: index of the Property_row_action
    };

    constexpr Property_row_key() = default;
    constexpr Property_row_key(const Property_row_id id, const uint64_t instance = 0)
        : m_kind{Kind::row}
        , m_id{static_cast<uint32_t>(id)}
        , m_instance{instance}
    {
    }
    constexpr Property_row_key(const Kind kind, const uint32_t id)
        : m_kind{kind}
        , m_id{id}
    {
    }

    [[nodiscard]] constexpr auto combine(const uint64_t scope) const -> uint64_t
    {
        const uint64_t kind_and_id = (static_cast<uint64_t>(m_kind) << 32) | static_cast<uint64_t>(m_id);
        return combine_property_row_scope(combine_property_row_scope(scope, kind_and_id), m_instance);
    }

private:
    Kind     m_kind    {Kind::row};
    uint32_t m_id      {0};
    uint64_t m_instance{0};
};

